# Values of the manuscript placeholders ([[...]]), from the outputs of scripts
# 01-06, written to output/placeholders.md. Also counts the testthat
# expectations of the test suite (runs the whole suite, about 10 minutes).
#
#   NOT_CRAN=true Rscript dev/supplementary/07_placeholders.R

source("dev/supplementary/00_setup.R")
Sys.setenv(NOT_CRAN = "true")

s1 <- readRDS(out("S1_batch.rds"))
s2 <- readRDS(out("S2_rnaseq_demo.rds"))
s3 <- readRDS(out("S3_microarray.rds"))
s4 <- readRDS(out("S4_performance.rds"))

# testthat expectations
tests <- as.data.frame(devtools::test(reporter = "silent", stop_on_failure = FALSE))
n_tests <- sum(tests$nb)
saveRDS(list(expectations = n_tests, tests = nrow(tests), failed = sum(tests$failed),
             skipped = sum(tests$skipped), files = length(unique(tests$file))),
        out("tests.rds"))

pct <- function(x) sprintf("%.1f", x)
perf <- s1$performance
cell <- function(strategy, column) {
  perf[perf$sdlog == 0.5 & perf$meta == "Fisher" & perf$strategy == strategy, column]
}
demo <- s2$summary[s2$summary$de_method == "DESeq2" & s2$summary$meta_method == "Fisher", ]
array_degs <- function(con) s3$summary$meta_degs[s3$summary$comparison == con]

# known low-CO2 genes that are meta-DEGs in both comparisons, as a short list
known <- s3$known
recovered <- known$expected[known$LC_3h_vs_HC_meta_deg & known$LC_24h_vs_HC_meta_deg]
known_text <- local({
  x <- recovered
  if (all(c("cmpA", "cmpB", "cmpC", "cmpD") %in% x)) x <- c(setdiff(x, c("cmpB", "cmpC", "cmpD")))
  x[x == "cmpA"] <- if (all(c("cmpA", "cmpB", "cmpC", "cmpD") %in% recovered)) "cmpA–D" else "cmpA"
  paste(x, collapse = ", ")
})

values <- data.frame(
  placeholder = c("BATCH_CHECK_FLAGGED", "BATCH_IGNORE_TPR", "BATCH_IGNORE_FDP", "BATCH_MODEL_TPR",
                  "BATCH_MODEL_FDP", "BATCH_COMBAT_TPR", "BATCH_COMBAT_FDP", "BATCH_REF_TPR",
                  "DEMO_NEW", "DEMO_SIDETRACKED", "DEMO_METHOD_OVERLAP", "ARRAY_GENES",
                  "ARRAY_DEG_3H", "ARRAY_DEG_24H", "ARRAY_KNOWN", "DEMO_APP_TIME", "N_TESTS"),
  value = c(
    sum(s1$batch_checks$flagged[s1$batch_checks$sdlog == 0.5]),
    pct(cell("Batch ignored", "tpr")), pct(cell("Batch ignored", "fdp")),
    pct(cell("Batch in the DE model", "tpr")), pct(cell("Batch in the DE model", "fdp")),
    pct(cell("ComBat-seq", "tpr")), pct(cell("ComBat-seq", "fdp")),
    pct(cell("No batch effect (reference)", "tpr")),
    demo$new, demo$sidetracked, pct(s2$method_overlap),
    s3$genes_kept, array_degs("LC_3h vs HC"), array_degs("LC_24h vs HC"), known_text,
    sprintf("%.1f", s4$rnaseq_median), n_tests),
  meaning = c(
    "studies (of 6) flagged by batch_check(), sdlog 0.5",
    "TPR (%), batch ignored, DESeq2 + Fisher, sdlog 0.5", "FDP (%), same",
    "TPR (%), batch in the DE model, DESeq2 + Fisher, sdlog 0.5", "FDP (%), same",
    "TPR (%), ComBat-seq, DESeq2 + Fisher, sdlog 0.5", "FDP (%), same",
    "TPR (%) without a batch effect (reference), DESeq2 + Fisher",
    sprintf("new DEGs, RNA-Seq demo, DESeq2 + Fisher (%s%% of the meta-DEGs)", demo$new_pct),
    sprintf("side-tracked DEGs, same (%s%% of the study DEGs)", demo$sidetracked_pct),
    sprintf("%% of the %d DESeq2 + Fisher meta-DEGs also found with edgeR and limma-voom (Fisher)",
            s2$reference_degs),
    "genes kept in the microarray demo after probe collapsing and intersection",
    "meta-analysis DEGs, LC_3h vs HC (2 studies)", "meta-analysis DEGs, LC_24h vs HC (3 studies)",
    sprintf("known low-CO2 genes that are up-regulated meta-DEGs in both comparisons (%d of %d checked)",
            length(recovered), nrow(known)),
    sprintf("seconds from click to results, RNA-Seq demo in the app (median of 3: %s)",
            paste(sprintf("%.1f", s4$app_times$rnaseq_demo_s), collapse = ", ")),
    sprintf("testthat expectations (%d tests in %d files; %d failed, %d skipped)",
            nrow(tests), length(unique(tests$file)), sum(tests$failed), sum(tests$skipped))),
  source = c(rep("S1 (S1_batch_check.csv, S1_batch_performance.csv)", 8),
             rep("S2 (S2_rnaseq_demo_methods.csv, S2_rnaseq_demo_overlap.csv)", 3),
             rep("S3 (S3_microarray_summary.csv, S3_microarray_known_genes.csv)", 4),
             "S4 (S4_app_times.csv)", "devtools::test()"))
save_table(values, "placeholders.csv")
md <- c("# Values of the manuscript placeholders",
        "",
        sprintf("Generated by `dev/supplementary/07_placeholders.R` on %s (%s).", format(Sys.Date()), session_line()),
        "",
        "| Placeholder | Value | Meaning | Source |",
        "|---|---|---|---|",
        sprintf("| `[[%s]]` | %s | %s | %s |", values$placeholder, values$value, values$meaning, values$source))
writeLines(md, out("placeholders.md"))
cat(md, sep = "\n")
